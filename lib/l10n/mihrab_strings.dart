String translateMihrab(String language, String source) {
  final index = const ['kk', 'ar', 'en'].indexOf(language);
  return index < 0 ? source : (_translations[source]?[index] ?? source);
}

extension MihrabStrings on BuildContext {
  String tr(String source) =>
      translateMihrab(Localizations.localeOf(this).languageCode, source);
  String hijriLabel(HijriDate date) =>
      '${date.day} ${tr(HijriDate.months[date.month - 1])} ${date.year} ${tr("г.х.")}';
}
